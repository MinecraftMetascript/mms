package sema

import (
	"fmt"
	"strconv"
	"strings"

	"github.com/minecraftmetascript/mms/engine/syntax"
)

// Expansion limits. Past the warning level the build still works; past
// twice the level it stops expanding with an error.
const (
	MaxIterations = 4096  // iterations of one build-time loop
	MaxDecls      = 10000 // declarations generated by loops, per project
)

// Origin records where a generated declaration came from.
type Origin struct {
	Template *syntax.Decl
	// Bindings are the loop variables and lets in scope, as
	// `name = value`, outermost first.
	Bindings []string
}

// Label describes the iteration, as in `b = "nether"`.
func (o *Origin) Label() string { return strings.Join(o.Bindings, ", ") }

// Expansion is the result of expanding a project's build-time items.
type Expansion struct {
	Consts *Consts
	Diags  map[string][]syntax.Diagnostic // by unit path
	// Templates maps each template declaration inside a loop or `if` to
	// the declarations made from it, in order.
	Templates map[*syntax.Decl][]*syntax.Decl
	// Info is editor information for build-time items outside
	// declarations: loop variables, lets and the consts they use.
	Info map[syntax.Node]*Info
	uses map[syntax.Node]*constEntry
}

func (x *Expansion) info(n syntax.Node) *Info {
	in := x.Info[n]
	if in == nil {
		in = &Info{}
		x.Info[n] = in
	}
	return in
}

// genKey identifies a generated declaration across analyses, so that an
// unchanged one keeps its node and its checked result.
type genKey struct {
	tmpl *syntax.Decl
	env  string
}

// Expand runs the build-time items of every unit: it evaluates loops,
// ifs and lets, checks Asserts, and sets each unit's Decls to the
// declarations that result, with their build-time scopes in Env.
func Expand(units []*Unit, defaultNS string) *Expansion {
	x := &Expansion{Consts: NewConsts(), Diags: map[string][]syntax.Diagnostic{}, Templates: map[*syntax.Decl][]*syntax.Decl{}, Info: map[syntax.Node]*Info{}, uses: map[syntax.Node]*constEntry{}}
	// Consts first: any declaration may use any Const.
	for _, u := range units {
		ns := defaultNS
		for _, d := range u.File.Decls {
			switch d.Kind.Name {
			case "Namespace":
				if d.Name != nil {
					ns = d.Name.Text
				}
			case "Const":
				if d.Name == nil {
					continue
				}
				id := d.Name.Text
				if !strings.Contains(id, ":") {
					id = ns + ":" + id
				}
				if x.Consts.byID[id] == nil {
					x.Consts.add(u, d, ns, id)
				}
			}
		}
	}
	total := 0
	for _, u := range units {
		e := &expander{x: x, u: u, total: &total, cache: u.gen, next: map[genKey]*syntax.Decl{}}
		u.Decls = nil
		u.Env = map[*syntax.Decl]*Env{}
		u.Origin = map[*syntax.Decl]*Origin{}
		root := NewEnv(x.Consts, defaultNS)
		e.items(u.File.Items, root, true)
		u.gen = e.next
	}
	for _, id := range sortedIDs(x.Consts.byID) {
		c := x.Consts.byID[id]
		x.Consts.get(c.ns, id) // evaluate unused consts too, for their errors
		x.Diags[c.unit.Path] = append(x.Diags[c.unit.Path], c.diags...)
	}
	return x
}

// Link connects consts to their symbols once the table exists.
func (x *Expansion) Link(t *Table) {
	for id, c := range x.Consts.byID {
		if s := t.Find("Const", id); s != nil && s.Decl == c.decl {
			c.sym = s
			s.Const = c.val
		}
	}
	for at, c := range x.uses {
		if c.sym != nil {
			in := x.info(at)
			in.Symbol, in.ID, in.Help = c.sym, c.sym.ID(), ""
		}
	}
}

type expander struct {
	x     *Expansion
	u     *Unit
	total *int
	cache map[genKey]*syntax.Decl
	next  map[genKey]*syntax.Decl
	// stopped is set once the declaration limit is passed.
	stopped bool
}

func (e *expander) report(code string, sev syntax.Severity, sp syntax.Span, format string, args ...any) {
	e.x.Diags[e.u.Path] = append(e.x.Diags[e.u.Path], syntax.Diagnostic{Code: code, Severity: sev, Sp: sp, Message: fmt.Sprintf(format, args...)})
}

func (e *expander) eval(env *Env, ex syntax.Expr) *Value {
	ev := &Evaluator{Env: env, ctx: "top", report: func(d syntax.Diagnostic) { e.x.Diags[e.u.Path] = append(e.x.Diags[e.u.Path], d) },
		Uses: func(c *constEntry, at syntax.Node) {
			if at != nil && e.x.Info[at] == nil {
				e.x.info(at)
				e.x.uses[at] = c
			}
		}}
	return ev.Eval(ex)
}

// items expands a list of items in one scope. top is set for the file's
// own top level, outside any loop or if.
func (e *expander) items(its []syntax.Item, env *Env, top bool) {
	for _, it := range its {
		if e.stopped {
			return
		}
		switch x := it.(type) {
		case *syntax.Decl:
			env = e.decl(x, env, top)
		case *syntax.TopLet:
			if x.Name == nil || x.Value == nil {
				if x.Name != nil {
					e.report("mms/missing-value", syntax.SeverityError, x.Sp, "a build-time let needs a value: let %s = ...", x.Name.Text)
				}
				continue
			}
			if v := e.eval(env, x.Value); v != nil {
				env = env.With(x.Name.Text, v)
				if e.x.Info[x.Name] == nil {
					e.x.info(x.Name).Local = &Local{Name: x.Name.Text, Type: "build-time " + kindWord(v), What: "let", Doc: x.Doc + "\n\nValue: `" + short(v.String()) + "`"}
				}
			}
		case *syntax.TopIf:
			e.topIf(x, env)
		case *syntax.TopFor:
			e.topFor(x, env)
		case *syntax.TopBlock:
			e.items(x.Items, env, false)
		}
	}
}

func (e *expander) topIf(x *syntax.TopIf, env *Env) {
	v := e.eval(env, x.Cond)
	if v == nil {
		return
	}
	if v.Kind != VBool {
		e.report("mms/type-mismatch", syntax.SeverityError, x.Cond.Span(), "a build-time if needs a bool, but this is %s", v.TypeName())
		return
	}
	if v.Bool {
		e.items(x.Then.Items, env, false)
		return
	}
	switch el := x.Else.(type) {
	case *syntax.TopIf:
		e.topIf(el, env)
	case *syntax.TopBlock:
		e.items(el.Items, env, false)
	}
}

func (e *expander) topFor(x *syntax.TopFor, env *Env) {
	if x.Var == nil {
		return
	}
	v := e.eval(env, x.Iter)
	if v == nil {
		return
	}
	if v.Kind == VWord {
		e.report("mms/not-constant", syntax.SeverityError, x.Iter.Span(), "'%s' is not a Const or build-time value; a loop at the top level goes over a list known at build time", v.Str)
		return
	}
	if v.Kind != VList {
		e.report("mms/type-mismatch", syntax.SeverityError, x.Iter.Span(), "a for loop goes over a list or a range, but this is %s", v.TypeName())
		return
	}
	n := len(v.Elems)
	if e.x.Info[x.Var] == nil {
		e.x.info(x.Var).Local = &Local{Name: x.Var.Text, Type: "build-time " + elemKinds(v), What: "for", Doc: "Values: `" + short(v.String()) + "`"}
		if in := e.x.info(x.Iter); in.Symbol == nil {
			in.Help = "Build-time loop: copies its body " + count(n, "time") + "."
		}
	}
	switch {
	case n > 2*MaxIterations:
		e.report("mms/expansion-limit", syntax.SeverityError, x.Iter.Span(), "this loop runs %d times; the limit is %d", n, 2*MaxIterations)
		return
	case n > MaxIterations:
		e.report("mms/expansion-limit", syntax.SeverityWarning, x.Iter.Span(), "this loop runs %d times; above %d builds get slow, and above %d they fail", n, MaxIterations, 2*MaxIterations)
	}
	for i, el := range v.Elems {
		scope := env
		if x.Index != nil {
			scope = scope.With(x.Index.Text, intValue(i))
		}
		scope = scope.With(x.Var.Text, el)
		e.items(x.Body.Items, scope, false)
		if e.stopped {
			return
		}
	}
}

// decl expands one declaration and returns the scope for what follows
// (a Namespace changes it).
func (e *expander) decl(d *syntax.Decl, env *Env, top bool) *Env {
	switch d.Kind.Name {
	case "Namespace":
		if !top {
			e.report("mms/misplaced", syntax.SeverityError, d.Kind.Sp, "Namespace goes at the top level, outside build-time loops and ifs")
			return env
		}
		e.u.Decls = append(e.u.Decls, d)
		if d.Name != nil {
			env = NewEnv(e.x.Consts, d.Name.Text)
		}
		e.u.Env[d] = env
		return env
	case "Const":
		if !top {
			e.report("mms/misplaced", syntax.SeverityError, d.Kind.Sp, "Const goes at the top level; inside a loop or if, use let")
			return env
		}
		e.u.Decls = append(e.u.Decls, d)
		e.u.Env[d] = env
		return env
	case "Assert":
		e.assert(d, env)
		return env
	}
	name := d.Name
	if d.Name != nil && d.Name.Quoted {
		ev := &Evaluator{Env: env, report: func(dg syntax.Diagnostic) { e.x.Diags[e.u.Path] = append(e.x.Diags[e.u.Path], dg) }}
		text, ok := ev.interpolate(d.Name.Text, d.Name.Sp, true)
		if !ok {
			return env
		}
		if text != d.Name.Text {
			name = &syntax.Name{Text: text, Sp: d.Name.Sp}
		}
	}
	if top && name == d.Name {
		e.u.Decls = append(e.u.Decls, d)
		e.u.Env[d] = env
		return env
	}
	*e.total++
	switch {
	case *e.total == MaxDecls+1:
		e.report("mms/expansion-limit", syntax.SeverityWarning, d.Kind.Sp, "build-time loops have made more than %d declarations; above %d the build fails", MaxDecls, 2*MaxDecls)
	case *e.total > 2*MaxDecls:
		e.report("mms/expansion-limit", syntax.SeverityError, d.Kind.Sp, "build-time loops made more than %d declarations; stopped here", 2*MaxDecls)
		e.stopped = true
		return env
	}
	key := genKey{tmpl: d, env: envKey(env, name)}
	g := e.cache[key]
	if g == nil {
		cp := *d
		cp.Name = name
		g = &cp
	}
	e.next[key] = g
	e.u.Decls = append(e.u.Decls, g)
	e.u.Env[g] = env
	if !top {
		e.u.Origin[g] = &Origin{Template: d, Bindings: env.Bindings()}
		e.x.Templates[d] = append(e.x.Templates[d], g)
	}
	return env
}

// envKey fingerprints a scope's bindings and a generated name.
func envKey(env *Env, name *syntax.Name) string {
	var b strings.Builder
	if name != nil {
		b.WriteString(name.Text)
	}
	b.WriteString("|" + env.NS)
	for s := env; s != nil; s = s.parent {
		for _, n := range s.order {
			b.WriteString("|" + n + "=" + s.vars[n].String())
		}
	}
	return b.String()
}

// assert checks `Assert "message" = condition`.
func (e *expander) assert(d *syntax.Decl, env *Env) {
	if d.Name == nil || !d.Name.Quoted {
		sp := d.Kind.Sp
		if d.Name != nil {
			sp = d.Name.Sp
		}
		e.report("mms/missing-value", syntax.SeverityError, sp, "Assert takes a message and a condition: Assert \"addresses are unique\" = Unique(addresses)")
		return
	}
	if d.Value == nil {
		e.report("mms/missing-value", syntax.SeverityError, d.Name.Sp, "Assert needs a condition after '='")
		return
	}
	v := e.eval(env, d.Value)
	if v == nil {
		return
	}
	if v.Kind != VBool {
		e.report("mms/type-mismatch", syntax.SeverityError, d.Value.Span(), "an Assert condition is a bool, but this is %s", v.TypeName())
		return
	}
	if !v.Bool {
		msg := d.Name.Text
		if b := env.Bindings(); len(b) > 0 {
			msg += " (when " + strings.Join(b, ", ") + ")"
		}
		e.report("mms/assert", syntax.SeverityError, d.Name.Sp, "%s", msg)
	}
}

// AllDecls lists every declaration written in a file, including those
// inside build-time loops and ifs, in source order.
func AllDecls(f *syntax.File) []*syntax.Decl {
	var out []*syntax.Decl
	var walk func(its []syntax.Item)
	walk = func(its []syntax.Item) {
		for _, it := range its {
			switch x := it.(type) {
			case *syntax.Decl:
				out = append(out, x)
			case *syntax.TopFor:
				walk(x.Body.Items)
			case *syntax.TopIf:
				walk(x.Then.Items)
				for el := x.Else; el != nil; {
					switch y := el.(type) {
					case *syntax.TopIf:
						walk(y.Then.Items)
						el = y.Else
					case *syntax.TopBlock:
						walk(y.Items)
						el = nil
					default:
						el = nil
					}
				}
			case *syntax.TopBlock:
				walk(x.Items)
			}
		}
	}
	walk(f.Items)
	return out
}

// iterLabel shortens an iteration list for messages: "a, b and 3 more".
func iterLabel(labels []string) string {
	if len(labels) <= 1 {
		return strings.Join(labels, "")
	}
	return labels[0] + ", and " + strconv.Itoa(len(labels)-1) + " more"
}
