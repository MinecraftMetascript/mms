// Models follow a parent chain: a model's textures fill slots, and the
// faces of the nearest model in the chain with elements name the slots
// they show as "#slot". A slot no model in the chain fills shows the
// missing texture.

// TextureSlot is a texture slot a model's parent chain uses or fills.
type TextureSlot struct {
	Name string
	// From is the model whose faces, or whose textures, lead to the
	// slot; for a slot no face shows (such as particle), the model that
	// fills it.
	From string
	// Used says faces of the chain show the slot: a face names it, or
	// names a slot that leads to it ("#down" is "#end" in cube_column),
	// and it is the last slot on the way, the one to fill.
	Used bool
	// Filled is what the chain's textures put there, such as
	// "minecraft:block/oak_log" or "#side"; "" when nothing does.
	Filled string
}

// modelInfo returns the slot facts of the model with the given full id:
// a project model's own, or vanilla's. ok is false when neither has it.
func (r *Result) modelInfo(id string) (*spec.ModelInfo, bool) {
	r.modelsOnce.Do(func() {
		r.models = map[string]*spec.ModelInfo{}
		for _, d := range r.Order {
			if d.Kind.Resource == "model" && d.Value != nil {
				r.models[d.ID()] = modelInfoOf(d.Value)
			}
		}
	})
	if m, ok := r.models[id]; ok {
		return m, true
	}
	if p, ok := strings.CutPrefix(id, "minecraft:"); ok && r.pack != nil {
		m, ok := r.pack.Models[p]
		return m, ok
	}
	return nil, false
}

// modelInfoOf reads a model file's parent, textures and the slots its
// elements use.
func modelInfoOf(v jsonv.Value) *spec.ModelInfo {
	o, _ := v.(*jsonv.Object)
	info := &spec.ModelInfo{}
	if o == nil {
		return info
	}
	if p, ok := o.Get("parent").(jsonv.String); ok {
		info.Parent = string(p)
	}
	if t, ok := o.Get("textures").(*jsonv.Object); ok {
		info.Textures = map[string]string{}
		for _, m := range t.Members {
			switch x := m.Value.(type) {
			case jsonv.String:
				info.Textures[m.Key] = string(x)
			case *jsonv.Object:
				if s, ok := x.Get("sprite").(jsonv.String); ok {
					info.Textures[m.Key] = string(s)
				}
			}
		}
	}
	if els, ok := o.Get("elements").(jsonv.Array); ok {
		info.Elements = true
		uses := map[string]bool{}
		for _, el := range els {
			eo, _ := el.(*jsonv.Object)
			if eo == nil {
				continue
			}
			faces, _ := eo.Get("faces").(*jsonv.Object)
			if faces == nil {
				continue
			}
			for _, f := range faces.Members {
				fo, _ := f.Value.(*jsonv.Object)
				if fo == nil {
					continue
				}
				if s, ok := fo.Get("texture").(jsonv.String); ok && strings.HasPrefix(string(s), "#") {
					uses[string(s)[1:]] = true
				}
			}
		}
		for s := range uses {
			info.Uses = append(info.Uses, s)
		}
		sort.Strings(info.Uses)
	}
	return info
}

// fullModelID gives a model id its namespace: minecraft when it has none,
// as the game reads it.
func fullModelID(id string) string {
	if strings.Contains(id, ":") {
		return id
	}
	return "minecraft:" + id
}

// ModelSlots returns the texture slots of model d's chain: those its
// elements use, and those its textures fill, sorted with the used ones
// first. known is false when the chain reaches a model neither the
// project nor vanilla has (it may come from another pack), or a loop.
func (r *Result) ModelSlots(d *Decl) (slots []TextureSlot, known bool) {
	self := modelInfoOf(d.Value)
	type link struct {
		id   string
		info *spec.ModelInfo
	}
	chain := []link{{d.ID(), self}}
	seen := map[string]bool{d.ID(): true}
	for cur := self; cur.Parent != ""; {
		id := fullModelID(cur.Parent)
		if strings.HasPrefix(id, "minecraft:builtin/") {
			break // generated by the game, such as builtin/generated
		}
		m, ok := r.modelInfo(id)
		if !ok || seen[id] {
			return nil, false
		}
		seen[id] = true
		chain = append(chain, link{id, m})
		cur = m
	}
	// Children's textures win over their parents'.
	textures := map[string]string{}
	filler := map[string]string{}
	for i := len(chain) - 1; i >= 0; i-- {
		for k, v := range chain[i].info.Textures {
			textures[k] = v
			filler[k] = chain[i].id
		}
	}
	var usedBy string
	var uses []string
	for _, l := range chain {
		if l.info.Elements {
			usedBy, uses = l.id, l.info.Uses
			break
		}
	}
	// A face's "#down" may lead on through "#end" before reaching a
	// texture: the last slot it reaches is the one to fill, as a
	// template's parameter.
	// by is the model that leads there last.
	leaf := func(slot, from string) (name, value, by string) {
		name, by = slot, from
		for i := 0; i < 32; i++ {
			next, ok := textures[name]
			if !ok {
				return name, "", by
			}
			if !strings.HasPrefix(next, "#") {
				return name, next, by
			}
			name, by = next[1:], filler[name]
		}
		return name, "", by
	}
	done := map[string]bool{}
	for _, u := range uses {
		name, value, by := leaf(u, usedBy)
		if !done[name] {
			slots = append(slots, TextureSlot{Name: name, From: by, Used: true, Filled: value})
			done[name] = true
		}
	}
	var rest []string
	for k := range textures {
		if !done[k] {
			rest = append(rest, k)
		}
	}
	sort.Strings(rest)
	for _, k := range rest {
		_, value, _ := leaf(k, "")
		slots = append(slots, TextureSlot{Name: k, From: filler[k], Filled: value})
	}
	return slots, true
}

// lintModelTexture reports a model whose elements show texture slots
// that nothing in its parent chain fills: the game shows the missing
// texture on those faces.
func lintModelTexture(l *lintRun) {
	for _, d := range l.r.Order {
		if d.Kind.Resource != "model" || d.Value == nil || hasErrors(d.Diags) || d.D == nil {
			continue
		}
		slots, known := l.r.ModelSlots(d)
		if !known {
			continue
		}
		var missing []string
		from := ""
		for _, s := range slots {
			if s.Used && s.Filled == "" {
				missing = append(missing, "#"+s.Name)
				from = s.From
			}
		}
		if len(missing) == 0 {
			continue
		}
		sp := d.D.Name.Sp
		if f := modelField(d.D, "textures"); f != nil {
			sp = f.Key.Sp
		}
		whose := "its elements use"
		if from != d.ID() {
			whose = fmt.Sprintf("the faces of '%s' use", strings.TrimPrefix(from, "minecraft:"))
		}
		noun := "slot"
		if len(missing) > 1 {
			noun = "slots"
		}
		msg := fmt.Sprintf("nothing fills the texture %s %s, which %s, so those faces show the missing texture", noun, strings.Join(missing, ", "), whose)
		l.out[d.Unit.Path] = append(l.out[d.Unit.Path], syntax.Diagnostic{Code: "lint/" + l.rule.ID, Severity: l.sev, Message: msg, Sp: sp})
	}
}

// modelField finds a top-level field of a model declaration's body.
func modelField(d *syntax.Decl, key string) *syntax.FieldStmt {
	b := d.Body
	if b == nil {
		if o, ok := d.Value.(*syntax.Object); ok {
			b = o.Body
		}
	}
	if b == nil {
		return nil
	}
	for _, it := range b.Items {
		if f, ok := it.(*syntax.FieldStmt); ok && f.Key.Text == key {
			return f
		}
	}
	return nil
}

// ModelTexturesBody returns the object body of a model declaration's
// textures field, or nil.
func ModelTexturesBody(d *syntax.Decl) *syntax.Block {
	if f := modelField(d, "textures"); f != nil {
		if o, ok := f.Value.(*syntax.Object); ok {
			return o.Body
		}
	}
	return nil
}

// RetextureSlots returns the texture slots of the models a prelude
// Retexture instance writes over, for completion in its textures body:
// those faces show first, each slot once. ok is false when d is not a
// Retexture instance's body.
func (r *Result) RetextureSlots(d *Decl) (slots []TextureSlot, ok bool) {
	if d == nil || d.Blueprint == nil || d.D == nil || d.Blueprint.D.NameText() != "Retexture" || !strings.HasPrefix(d.Blueprint.Path, prelude.Prefix) || r.Eval == nil {
		return nil, false
	}
	emitted := map[*syntax.Decl]bool{}
	for _, f := range r.Eval.Files {
		for _, e := range f.Decls {
			if e.Instance != nil && e.Instance.D == d.D {
				emitted[e.D] = true
			}
		}
	}
	// A slot one model shows and another only fills counts as shown.
	var names []string
	best := map[string]TextureSlot{}
	for _, m := range r.Order {
		if !emitted[m.D] || m.Kind.Resource != "model" {
			continue
		}
		ms, _ := r.ModelSlots(m)
		for _, s := range ms {
			prev, ok := best[s.Name]
			if !ok {
				names = append(names, s.Name)
			}
			if !ok || s.Used && !prev.Used {
				best[s.Name] = s
			}
		}
	}
	var used, rest []TextureSlot
	for _, n := range names {
		if s := best[n]; s.Used {
			used = append(used, s)
		} else {
			rest = append(rest, s)
		}
	}
	return append(used, rest...), true
}
